    private void botonCalcularAreaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonCalcularAreaActionPerformed
        if (opcionRectangulo.isSelected()) {
            if (cajaBase.getText().equals("") || cajaAltura.getText().equals("")) {
                JOptionPane.showMessageDialog(rootPane, "Llene las cajas de texto", "Error", 2);
            } else {
                try {
                    double base = Double.parseDouble(cajaBase.getText());
                    double altura = Double.parseDouble(cajaAltura.getText());

                    Rectangulo figura = new Rectangulo();
                    cajaArea.setText(String.valueOf(figura.area(base, altura)));

                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(rootPane, "Llene las cajas de texto", "Error", 2);
                }

            }
        }
        if (opcionTriangulo.isSelected()) {
            if (cajaBase.getText().equals("") || cajaAltura.getText().equals("")) {
                JOptionPane.showMessageDialog(rootPane, "Llene las cajas de texto", "Error", 2);
            } else {
                try {
                    double base = Double.parseDouble(cajaBase.getText());
                    double altura = Double.parseDouble(cajaAltura.getText());

                    Triangulo figura = new Triangulo();
                    cajaArea.setText(String.valueOf(figura.area(base, altura)));

                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(rootPane, "Llene las cajas de texto", "Error", 2);
                }

            }
        }
        if (opcionCirculo.isSelected()) {
            if (cajaRadio.getText().equals("")) {
                JOptionPane.showMessageDialog(rootPane, "Llene las cajas de texto", "Error", 2);
            } else {
                try {
                    double radio = Double.parseDouble(cajaRadio.getText());
                    Circulo figura = new Circulo();
                    cajaArea.setText(String.valueOf(figura.area(radio)));

                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(rootPane, "Llene las cajas de texto", "Error", 2);
                }

            }
        }
    }//GEN-LAST:event_botonCalcularAreaActionPerformed

