    private void botonGuardarResultadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonGuardarResultadoActionPerformed
    File area = new File("area.txt");
        try {
            if (area.createNewFile()) {
                FileWriter escritor = new FileWriter(area);
                escritor.write("Area de la figura");
                escritor.write(cajaArea.getText());
                escritor.close();
                System.out.println("Archivo creado con exito");
            } else {

                FileWriter escritor = new FileWriter(area);
                escritor.write("Area de la figura: ");
                escritor.write(cajaArea.getText());
                escritor.close();
                System.out.println("Archivo sobreescrito con exito");
            }
        } catch (IOException e) {
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_botonGuardarResultadoActionPerformed


